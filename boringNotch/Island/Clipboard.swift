import AppKit
import Defaults
import SwiftUI

struct ClipItem: Codable, Identifiable, Hashable {
    var id = UUID()
    var text: String
    var date = Date()
}

extension Defaults.Keys {
    static let islandClipboardLimit = Key<Int>("islandClipboardLimit", default: 50)
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [ClipItem] = []

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// Markers password managers set on entries that must not be recorded.
    private let skippedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    private init() {
        items = IslandStore.load("clipboard", as: [ClipItem].self) ?? []
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard NotchViews.clipboard.isVisible else { return }

        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !types.contains(where: skippedTypes.contains) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text), at: 0)
        items = Array(items.prefix(Defaults[.islandClipboardLimit]))
        save()
    }

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        save()
    }

    private func save() {
        IslandStore.save(items, as: "clipboard")
    }
}

struct ClipboardView: View {
    @EnvironmentObject var vm: BoringViewModel
    @ObservedObject private var history = ClipboardHistory.shared
    @State private var copiedID: UUID?

    var body: some View {
        if history.items.isEmpty {
            IslandEmptyState(icon: "doc.on.clipboard", text: String(localized: "Noch nichts kopiert"))
        } else {
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 8) {
                    ForEach(history.items) { item in
                        card(for: item)
                    }
                }
                .padding(.horizontal, 4)
            }
            .frame(maxWidth: .infinity, maxHeight: .infinity)
        }
    }

    private func card(for item: ClipItem) -> some View {
        Button {
            history.copy(item)
            copiedID = item.id
            Task {
                try? await Task.sleep(for: .milliseconds(450))
                vm.close()
                copiedID = nil
            }
        } label: {
            VStack(alignment: .leading, spacing: 4) {
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.caption)
                    .foregroundStyle(.white)
                    .lineLimit(5)
                    .multilineTextAlignment(.leading)
                    .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                Text(copiedID == item.id ? String(localized: "Kopiert") : item.date.formatted(.relative(presentation: .named)))
                    .font(.caption2)
                    .foregroundStyle(copiedID == item.id ? .green : .secondary)
            }
            .padding(8)
            .frame(width: 150, height: 104)
            .background(RoundedRectangle(cornerRadius: 12).fill(Color.white.opacity(0.07)))
            .contentShape(RoundedRectangle(cornerRadius: 12))
        }
        .buttonStyle(IslandTileStyle())
        .contextMenu {
            Button(String(localized: "Eintrag löschen")) { history.remove(item) }
            Button(String(localized: "Gesamten Verlauf löschen")) { history.clear() }
        }
        .help(String(localized: "Klicken, um wieder in die Zwischenablage zu kopieren"))
    }
}

struct IslandEmptyState: View {
    let icon: String
    let text: String

    var body: some View {
        VStack(spacing: 8) {
            Image(systemName: icon)
                .font(.title)
            Text(text)
                .font(.callout)
        }
        .foregroundStyle(.secondary)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }
}
